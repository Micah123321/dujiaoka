const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = require('./.runtime/browser/node_modules/playwright');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = 'http://127.0.0.1:8097';
  await page.goto(base);
  await page.locator('.product-card').waitFor();
  assert.equal(await page.locator('.product-card').count(), 1);
  await page.getByRole('searchbox').fill('不存在的商品');
  await page.getByText('暂时没有找到商品').waitFor();
  await page.getByRole('button', { name: '查看全部商品' }).click();
  await page.locator('.product-card').waitFor();
  await page.locator('.product-card img').evaluateAll(images => Promise.all(images.map(image => image.decode().catch(() => {}))));
  await page.screenshot({ path: path.join(__dirname, '.runtime/modern-desktop.png'), fullPage: true });
  await page.locator('.product-card').click();
  await page.locator('input[name="email"]').waitFor();
  await page.locator('input[name="by_amount"]').fill('2');
  assert.match(await page.locator('.total').innerText(), /18[.]00/);
  assert.ok((await page.locator('input[name="_token"]').inputValue()).length > 20);
  await page.locator('input[name="email"]').fill('fixture@example.test');
  await page.locator('input[name="search_pwd"]').fill('fixture-password');
  let posted;
  await page.route('**/create-order', async route => { posted = route.request().postData(); await route.fulfill({status:200, contentType:'text/html', body:'<h1>Fixture submitted</h1>'}); });
  await page.getByRole('button', {name: '提交订单 →'}).click();
  await page.getByRole('heading', {name:'Fixture submitted'}).waitFor();
  const fields = new URLSearchParams(posted);
  assert.equal(fields.get('by_amount'), '2');
  assert.equal(fields.get('gid'), '1');
  assert.equal(fields.get('payway'), '1');
  await page.goto(base + '/order-search');
  await page.getByRole('button', {name:'邮箱查询', exact:true}).click();
  assert.match(await page.locator('form').getAttribute('action'), /search-order-by-email$/);
  await page.locator('input[name="search_pwd"]').waitFor();
  await page.getByRole('button', {name:'浏览器记录', exact:true}).click();
  assert.match(await page.locator('form').getAttribute('action'), /search-order-by-browser$/);
  await page.goto(base + '/detail-order-sn/FIXTUREORDER0001');
  await page.locator('textarea').waitFor();
  assert.equal(await page.locator('textarea').inputValue(), 'FIXTURE-CARD');
  await page.getByRole('button', {name:'复制内容'}).click();
  await page.getByText('已复制到剪贴板').waitFor();
  await page.route('**/check-order-status/**', route => route.fulfill({json:{code:400001}}));
  await page.goto(base + '/qrpay');
  await page.getByText('订单已过期，请返回店铺重新下单。').waitFor();
  assert.equal(await page.getByRole('button', {name:'我已支付，查询状态'}).count(), 0);
  await page.setViewportSize({width:390, height:844});
  for (const route of ['/', '/buy/1', '/order-search', '/bill/FIXTUREORDER0001', '/detail-order-sn/FIXTUREORDER0001', '/qrpay']) {
    await page.goto(base + route);
    await page.locator('.site-header').waitFor();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Mobile overflow: ' + route);
  }
  await page.goto(base);
  await page.locator('.product-card').waitFor();
  await page.screenshot({path:path.join(__dirname, '.runtime/modern-mobile.png'), fullPage:true});
  await page.unroute('**/check-order-status/**');
  await page.route('**/check-order-status/**', route => route.fulfill({json:{code:200}}));
  await page.goto(base + '/qrpay');
  await page.waitForURL('**/detail-order-sn/FIXTUREORDER0001');
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: desktop/mobile rendering, search, purchase POST, query modes, expiry, no JS errors');
})().catch(error => { console.error(error); process.exit(1); });
